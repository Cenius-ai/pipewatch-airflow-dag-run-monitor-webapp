#!/usr/bin/env bash
# Pipewatch installer: dependencies -> database -> demo data. It never starts the
# server (that is a separate command) and it is safe to run more than once.
set -eu   # POSIX-safe: works with both `sh install.sh` and `bash install.sh`
cd "$(dirname "$0")"

PYTHON_BIN="${PYTHON_BIN:-python3}"

echo "==> Pipewatch: installing Python dependencies ($("$PYTHON_BIN" --version 2>&1))"
"$PYTHON_BIN" -m pip install --quiet --upgrade pip setuptools wheel
"$PYTHON_BIN" -m pip install --quiet -r requirements.txt

if [ ! -f .env ]; then
  echo "==> Pipewatch: writing .env with a generated session secret"
  SECRET="$("$PYTHON_BIN" -c 'import secrets; print(secrets.token_hex(32))')"
  {
    echo "# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
    echo "# Delete this file to fall back to the in-code development key."
    echo "SECRET_KEY=${SECRET}"
  } > .env
fi

echo "==> Pipewatch: creating the SQLite schema and seeding demo data"
"$PYTHON_BIN" -m pipewatch.seed

echo "==> Pipewatch: verifying the app module imports cleanly"
"$PYTHON_BIN" -c "import app" >/dev/null

cat <<'MSG'

Install complete. Nothing else to configure.

  Start the dashboard : python3 app.py
  Open                : http://127.0.0.1:8050
  Demo sign-in        : cenius / cenius   (or airflow / airflow-demo)
  Run the tests       : python3 -m pytest

MSG
